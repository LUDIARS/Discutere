// String#normalize("NFKC") の 1 文字ごとの対応表と、結合文字の合成表を Node から書き出す。
// 実行: npx tsx native/tests/golden/w1-F-nfkc-table.gen.ts
// 出力: native/src/flow/user_voices/nfkc_table.inc (C++ の配列。steam-app の normalizeGameName が使う)
//
// ICU を持ち込まずに NFKC を近似するための表 (完全な NFKC ではない。差は port-notes/w1-F.md)。
//   - kMap:  NFKC(c) !== c となる 1 文字 c → 置き換え後の code point 列
//   - kComp: (基底, 結合文字) → 合成済み 1 文字 (NFC で 1 文字になる組だけ)
import fs from "node:fs";
import path from "node:path";

const maps: Array<[number, number[]]> = [];
for (let cp = 0; cp < 0x30000; cp++) {
  if (cp >= 0xd800 && cp < 0xe000) continue;
  const s = String.fromCodePoint(cp);
  const n = s.normalize("NFKC");
  if (n !== s) maps.push([cp, Array.from(n).map((c) => c.codePointAt(0)!)]);
}

const ranges: Array<[number, number]> = [
  [0x41, 0x24f],
  [0x370, 0x3ff],
  [0x400, 0x4ff],
  [0x1e00, 0x1fff],
  [0x3041, 0x30ff],
];
const marks: number[] = [];
for (let m = 0x300; m <= 0x36f; m++) marks.push(m);
marks.push(0x3099, 0x309a);
const comps: Array<[number, number, number]> = [];
for (const [lo, hi] of ranges) {
  for (let base = lo; base <= hi; base++) {
    for (const mark of marks) {
      const composed = (String.fromCodePoint(base) + String.fromCodePoint(mark)).normalize("NFC");
      const cps = Array.from(composed);
      if (cps.length === 1) comps.push([base, mark, cps[0].codePointAt(0)!]);
    }
  }
}
comps.sort((a, b) => a[0] - b[0] || a[1] - b[1]);

const pool: number[] = [];
const entries: string[] = [];
for (const [cp, out] of maps) {
  entries.push(`{0x${cp.toString(16)}, ${pool.length}, ${out.length}}`);
  pool.push(...out);
}
const lines: string[] = [];
lines.push("// Generated by native/tests/golden/w1-F-nfkc-table.gen.ts (Node " + process.version + "). Do not edit.");
lines.push(`static constexpr std::uint32_t kNfkcPool[${pool.length}] = {`);
for (let i = 0; i < pool.length; i += 16) lines.push("    " + pool.slice(i, i + 16).map((v) => `0x${v.toString(16)}`).join(", ") + ",");
lines.push("};");
lines.push(`static constexpr NfkcEntry kNfkcMap[${entries.length}] = {`);
for (let i = 0; i < entries.length; i += 6) lines.push("    " + entries.slice(i, i + 6).join(", ") + ",");
lines.push("};");
lines.push(`static constexpr NfkcCompose kNfkcCompose[${comps.length}] = {`);
for (let i = 0; i < comps.length; i += 6)
  lines.push("    " + comps.slice(i, i + 6).map(([a, b, c]) => `{0x${a.toString(16)}, 0x${b.toString(16)}, 0x${c.toString(16)}}`).join(", ") + ",");
lines.push("};");

const out = path.join(path.dirname(new URL(import.meta.url).pathname), "..", "..", "src", "flow", "user_voices", "nfkc_table.inc");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, lines.join("\n") + "\n");
console.log(`wrote ${maps.length} maps, ${comps.length} compositions, pool ${pool.length}`);
