/**
 * 議題文 → 検索キーワード抽出 (外部の声 RAG / 情報ゲートの材料検索用)。
 *
 * 形態素解析器は持たない (依存ゼロ方針) ため、句読点・空白・代表的な助詞/接続で
 * 素朴に分割し、長さ 2 以上の語を拾う。フル議題文をそのまま 1 語で `includes` 照合すると
 * 日本語議題はほぼ一致せず材料 0 件になる (実害: 「モンスターストライクの引っ張り…」)
 * のを避けるのが目的。完全な分かち書きは狙わず、ゲーム名・主要語が 1 語として残れば十分。
 *
 * 略称⇄正式名の対応 (例: モンスト⇄モンスターストライク) はここでは解決しない
 * (別途エイリアス辞書が要る = 既知の follow-up)。純関数 — 単体テスト可能。
 */

/** キーワードとして無意味な定型・汎用語 (拾っても材料を絞れない)。 */
const STOP = new Set([
  "について",
  "とは",
  "なぜ",
  "どう",
  "どこ",
  "面白い",
  "面白いか",
  "面白さ",
  "本当に",
  "ゲーム",
  "こと",
  "もの",
  "それ",
  "これ",
  "ため",
]);

/**
 * 分割境界: 句読点・空白・括弧、および代表的な助詞/接続詞。
 * 複数文字 (について 等) を単一文字 (の は 等) より前に置き、貪欲に食わせる。
 * 単一文字助詞は **ひらがな** のみ対象 (カタカナのゲーム名「ハンター」等を割らない)。
 */
const SPLIT =
  /[\s、。，．・,.;:：；「」『』（）()【】\[\]"'!?！？〜~…\/|]+|について|という|からは|までに|だろう|でしょう|ですか|なのか|から|まで|より|など|って|とか|けど|[のはがをにへとやもでか]/gu;

/**
 * 議題語 (terms) を検索キーワードに分解する。
 * @param terms 議題文など (通常 1 要素)。
 * @param max 返すキーワードの最大数 (specific=長い語を優先)。
 */
export function extractKeyTerms(terms: readonly string[], max = 6): string[] {
  const out = new Set<string>();
  for (const raw of terms) {
    if (typeof raw !== "string") continue;
    for (const piece of raw.toLowerCase().split(SPLIT)) {
      const t = piece.trim();
      if (t.length >= 2 && !STOP.has(t)) out.add(t);
    }
  }
  // 長い語ほど specific (ゲーム名等) なので優先して残す。
  return [...out].sort((a, b) => b.length - a.length).slice(0, max);
}
